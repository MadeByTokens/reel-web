import { test } from '@playwright/test';
import { addAudio, addLayerMedia, addMedia, addText, frames, newProject, openApp, project, seek, select } from './helpers';

// Screenshots for inspection by eye; nothing is asserted here.
const shot = (name: string, project: string): string => `test-results/shots/${project}-${name}.png`;

test('screens', async ({ page }, info) => {
  const tag = info.project.name;
  const errors = await openApp(page);
  await page.screenshot({ path: shot('01-home-empty', tag) });
  await page.locator('#home-create').click();
  await page.screenshot({ path: shot('02-new-project', tag) });
  await page.getByRole('button', { name: 'Cancel' }).click();
  await newProject(page, 'Holiday');
  await page.screenshot({ path: shot('03-editor-empty', tag) });

  const video = info.project.name.includes('chromium');
  if (video) await addMedia(page, 'clip.mp4', 'blue.webm');
  await addMedia(page, 'red.png', 'green.png');
  await addLayerMedia(page, 'green.png');
  await seek(page, 0.5);
  await addText(page, 'Hello Reel');
  await addAudio(page, 'tone.wav');
  await select(page, null);
  await seek(page, 1);
  await page.waitForTimeout(800);
  await page.screenshot({ path: shot('04-editor', tag) });

  const p = await project(page);
  await select(page, p.primary[0]!.id);
  await page.screenshot({ path: shot('05-clip-options', tag) });
  await page.getByRole('button', { name: 'Trim / Split' }).click();
  await page.screenshot({ path: shot('06-trim', tag) });
  await select(page, p.layers.find((c) => c.kind === 'text')!.id);
  await frames(page, 3);
  await page.screenshot({ path: shot('07-text-selected', tag) });
  await page.getByRole('button', { name: 'Font' }).click();
  await page.screenshot({ path: shot('08-font', tag) });
  await select(page, p.audio[0]!.id);
  await page.getByRole('button', { name: 'Mixer' }).click();
  await page.screenshot({ path: shot('09-mixer', tag) });
  // Transitions, keyframes, effects and stickers.
  const cuts = (await project(page)).primary;
  await page.locator('.junction').last().click();
  await page.getByRole('button', { name: 'Crossfade' }).click();
  await seek(page, cuts[cuts.length - 1]!.start - 0.5);
  await frames(page, 3);
  await page.screenshot({ path: shot('14-transition', tag) });
  const picture = p.layers.find((c) => c.kind === 'image')!;
  await select(page, picture.id);
  await seek(page, picture.start);
  await page.getByRole('button', { name: 'Keyframes' }).click();
  await page.getByRole('button', { name: 'Add keyframe' }).click();
  await seek(page, picture.start + 2);
  await page.getByRole('button', { name: 'Add keyframe' }).click();
  await page.screenshot({ path: shot('15-keyframes', tag) });
  await page.getByRole('button', { name: 'Back' }).click();
  await page.screenshot({ path: shot('16-layer-options', tag) });
  await page.getByRole('button', { name: 'Chroma Key' }).click();
  await page.screenshot({ path: shot('17-chroma', tag) });
  await page.getByRole('button', { name: 'Back' }).click();
  await page.getByRole('button', { name: 'Color Filter' }).click();
  await page.getByRole('button', { name: 'Vintage' }).click();
  await page.screenshot({ path: shot('18-filter', tag) });
  await page.getByRole('button', { name: 'Back' }).click();
  await page.getByRole('button', { name: 'Adjustment' }).click();
  await page.screenshot({ path: shot('19-adjust', tag) });
  await select(page, null);
  await page.locator('#add-layer').click();
  await page.screenshot({ path: shot('20-layer-menu', tag) });
  await page.locator('#layer-sticker').click();
  await page.screenshot({ path: shot('21-stickers', tag) });
  await page.getByRole('button', { name: 'Sticker 😎' }).click();
  await frames(page, 3);
  await page.screenshot({ path: shot('22-sticker-placed', tag) });

  await select(page, null);
  await page.locator('#export-button').click();
  await page.screenshot({ path: shot('10-export', tag) });
  await page.getByRole('button', { name: 'Cancel' }).click();
  await page.locator('#menu-button').click();
  await page.screenshot({ path: shot('11-menu', tag) });
  await page.locator('#menu-help').click();
  await page.screenshot({ path: shot('12-help', tag) });
  await page.locator('#help-close').click();
  await page.locator('#back').click();
  await page.locator('#home-create').waitFor();
  await page.screenshot({ path: shot('13-home', tag) });
  if (errors.length) throw new Error(`Page errors: ${errors.join(' | ')}`);
});
